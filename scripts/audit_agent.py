#!/usr/bin/env python3
import os
import subprocess
from pathlib import Path

# Repository root path
REPO_ROOT = Path(__file__).parent.parent.resolve()
APP_CODE = REPO_ROOT / "app-code"
ARGOCD_APPS = REPO_ROOT / "argocd-apps"
CONTEXT_DIR = REPO_ROOT / "context"

def run_cmd(cmd):
    """Utility to run terminal shell commands cleanly."""
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=REPO_ROOT)
    return result.stdout.strip()

def generate_state_md():
    """Scans app-code and argocd-apps to generate context/state.md."""
    apps = []
    
    if APP_CODE.exists():
        for app_dir in sorted(APP_CODE.glob("*")):
            if not app_dir.is_dir():
                continue
            
            app_name = app_dir.name
            argocd_wrapper = ARGOCD_APPS / f"{app_name}-app.yaml"
            wrapper_status = "✅ Present" if argocd_wrapper.exists() else "❌ Missing"
            
            namespaces = set()
            host_paths = set()
            ingresses = set()
            
            for yaml_file in app_dir.glob("*.yaml"):
                content = yaml_file.read_text(errors="ignore")
                for line in content.splitlines():
                    line_str = line.strip()
                    if line_str.startswith("namespace:"):
                        namespaces.add(line_str.split(":", 1)[1].strip())
                    if "path:" in line_str and ("/mnt/" in line_str or "/data" in line_str):
                        host_paths.add(line_str.split(":", 1)[1].strip())
                    if "host:" in line_str:
                        ingresses.add(line_str.split(":", 1)[1].strip().strip('"').strip("'"))

            apps.append({
                "name": app_name,
                "wrapper": wrapper_status,
                "namespace": ", ".join(namespaces) if namespaces else "default",
                "host_paths": ", ".join(host_paths) if host_paths else "None",
                "ingresses": ", ".join(ingresses) if ingresses else "None"
            })

    content = "# Elysium K3s Cluster: Live Manifest Inventory\n\n"
    content += "This file is automatically generated by `scripts/audit_agent.py`.\n\n"
    content += "| Application | ArgoCD Wrapper | Namespace | HostPath Mounts | Ingress Hostnames |\n"
    content += "| :--- | :--- | :--- | :--- | :--- |\n"
    for app in apps:
        content += f"| **{app['name']}** | {app['wrapper']} | `{app['namespace']}` | `{app['host_paths']}` | `{app['ingresses']}` |\n"
    
    (CONTEXT_DIR / "state.md").write_text(content)
    print(" [✓] Generated context/state.md")

