def sync_to_github():
    """Stages, commits, and pushes context files to GitHub."""
    print(" 🚀 Syncing files to GitHub...")
    run_cmd("git add context/architecture.md context/context.md context/state.md")
    
    status = run_cmd("git status --porcelain context/")
    if not status:
        print(" ℹ️ No documentation changes detected. Skipping git push.")
        return

    run_cmd('git commit -m "chore(audit): update context architecture, state, and context files"')
    push_output = run_cmd("git push origin main")
    print(" [✓] Successfully committed and pushed context files to GitHub!")

if __name__ == "__main__":
    CONTEXT_DIR.mkdir(exist_ok=True)
    print("🔍 Running Elysium Cluster Audit Agent...")
    generate_state_md()
    generate_context_md()
    generate_architecture_md()
    sync_to_github()
